    SX.forEach((x, k) => fl.push({ k, t0: c.soavt - .05 + ord(k) * .04, dur: .6 }));                 // «соавтор»
    fl.forEach((F, n) => { F.arr = F.t0 + F.dur; F.cell = pick([(SX[F.k] - 180) / 180 * .95, .42 + .28 * H(n * 2.7), .8], F.arr); });
    const free = G.map((g, i) => i).filter(i => !taken.has(i));
