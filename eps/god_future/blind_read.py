"""Материалы слепой читки текста (docs/FORMAT.md «Слепая вычитка текста»; владелец 05.11: «всё должно быть понятно,
одно выходит из другого, не должны свайпать»).

    python3 eps/god_future/blind_read.py <текст.md> <папка_раунда>

Текст — строки «NN. фраза» под заголовками «## Часть N …»; квадратные скобки [карточка: …] остаются как надпись.
Для каждой части пишет <папка>/pN/: 00_intro.md (что делать читателю), seg01.md… (одна фраза = один отрезок, с
примерным временем от начала ролика), zz_questions.md. Читатель (роль serial-viewer) получает только эту папку:
ни брифа, ни замысла, ни прошлых версий, ни другой части.
"""
from pathlib import Path
import re
import sys

WPS = 2.36  # Brian 1.22 в universe_net_p1: 358 слов за 151,5 с вместе с паузами

INTRO = """# Вводная

Ты листаешь ленту коротких вертикальных видео (YouTube Shorts / Instagram Reels). Попалось научно-популярное видео.
Звука и картинки здесь нет — только текст закадрового голоса, по одной фразе на отрезок, с примерным временем от начала
видео. Субтитры этого текста идут на экране с первого кадра.

Читай отрезки строго по порядку: seg01.md, seg02.md, … Ответ на отрезок пиши сразу после его чтения и до того, как открыл
следующий; к прошлым отрезкам не возвращайся и прошлые ответы не исправляй. Не ищи ничего в интернете и не открывай
других файлов.

На каждый отрезок ответь коротко, своими словами персоны:
1. Что понял (одной фразой).
2. Почему это говорят сейчас? Вытекает ли это из прошлой фразы? Ответ: «вытекает» / «шероховато» / «разрыв» — и почему.
   Разрыв — если связь приходится додумывать самому.
3. Что непонятно: слово, имя, логический шаг, число.
4. Свайпнул бы здесь? «нет» / «может быть» / «да» — и почему (скучно, непонятно, обидно, неправдоподобно, затянуто…).
5. Интерес сейчас: 1–5.

После последнего отрезка — «## Пересказ»: перескажи видео своими словами, как другу, 3–5 фраз. Потом открой zz_questions.md.
"""

QUESTIONS = """# Вопросы после просмотра

1. Какой вопрос видео задало в начале? Получил ли ты на него ответ в этом же видео? Если нет — чувствуешь себя обманутым?
2. Главная мысль видео — одной фразой.
3. Где была самая слабая связь между соседними фразами (номер отрезка) и как бы ты её починил?
4. Где ты, скорее всего, ушёл бы из видео (номер отрезка)? Почему?
5. Какие утверждения показались неправдой, натяжкой или пересказом с чужих слов? Какие факты хочется проверить?
6. Что могло задеть или обидеть верующего или неверующего зрителя? Конкретные слова.
7. Финал: он вытекает из сказанного или появляется из ниоткуда? Хочется ли посмотреть следующую / предыдущую часть?
8. Оценка всего видео 1–10 и одна главная правка.
"""


def parts(text):
    out, cur = {}, None
    for line in text.splitlines():
        m = re.match(r"^##\s*Часть\s*(\d+)", line)
        if m:
            cur = out.setdefault(int(m.group(1)), [])
            continue
        m = re.match(r"^\s*(\d+[а-яa-z]?)\.\s+(.+)$", line)
        if m and cur is not None:
            cur.append(m.group(2).strip())
    return out


def main(src, dst):
    dst = Path(dst)
    for n, phrases in parts(Path(src).read_text()).items():
        d = dst / f"p{n}"
        d.mkdir(parents=True, exist_ok=True)
        (d / "00_intro.md").write_text(INTRO)
        (d / "zz_questions.md").write_text(QUESTIONS)
        t = 0.0
        for i, ph in enumerate(phrases, 1):
            spoken = re.sub(r"\[[^\]]*\]", "", ph).strip()
            card = re.findall(r"\[([^\]]*)\]", ph)
            body = f"# Отрезок {i} из {len(phrases)} · ≈{int(t // 60)}:{int(t % 60):02d}\n\nГолос: {spoken}\n"
            if card:
                body += "\nНадпись на экране в конце: " + "; ".join(c.split(":", 1)[-1].strip() for c in card) + "\n"
            (d / f"seg{i:02d}.md").write_text(body)
            t += len(spoken.split()) / WPS
        print(f"p{n}: {len(phrases)} отрезков, ≈{int(t // 60)}:{int(t % 60):02d} -> {d}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
