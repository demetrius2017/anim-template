"""Материалы слепого просмотра готового ролика (CLAUDE.md п.17 студии; docs/FORMAT.md): листы кадров с РЕАЛЬНОЙ
сжатой копии (qa_deliver.py части → qa/blind_view/pN_sheet_K.jpg) + закадровый текст с таймкодами (pN_text.md).

    python3 eps/god_future/blind_view.py <папка_раунда>

Для каждой части пишет <папка>/pN/: 00_intro.md, seg01.md + seg01.jpg (минута 1), seg02.md + seg02.jpg …, zz_questions.md.
Зритель (роль serial-viewer) читает только эту папку: ни брифа, ни раскадровки, ни прошлых версий, ни другой части.
"""
from pathlib import Path
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[2]

INTRO = """# Вводная

Ты листаешь ленту коротких вертикальных видео (YouTube Shorts / Instagram Reels). Попалось научно-популярное видео.
Посмотреть его можно только так: листы кадров (кадр каждые 2 секунды, 6 в ряд, 5 рядов — 30 кадров = 1 минута на лист)
и текст закадрового голоса с временем начала каждой фразы. Субтитры видны на самих кадрах.

Порядок: seg01.md (текст этой минуты) и seg01.jpg (её кадры), потом seg02.md и seg02.jpg, … Ответ на минуту пиши сразу
после неё и до следующей; к прошлым не возвращайся. Не открывай других файлов и ничего не ищи.

На каждую минуту ответь коротко, голосом своей персоны:
1. Что происходит — своими словами.
2. Совпадает ли картинка со словами? Где картинка непонятна или не про то (кадр № на листе).
3. Где связь между фразами пришлось додумывать (разрыв)?
4. Где бы ты свайпнул и почему (скучно, непонятно, статично, мелко, обидно…)?
5. Что мелко, не читается или закрыто на телефоне (подписи, люди, предметы)?
6. Интерес 1–5.

После последней минуты — «## Пересказ» (3–5 фраз, как другу), затем открой zz_questions.md.
Последнее твоё сообщение — все ответы целиком (## seg01 …, ## Пересказ, ## zz_questions): вызывающий видит только его.
"""

QUESTIONS = """# Вопросы после просмотра

1. Первый кадр (кадр 1 листа 1): понятно ли без звука, о чём видео? Остановился бы?
2. Главная мысль видео — одной фразой.
3. Какие кадры запомнились? Какие кадры непонятны (лист, номер кадра)?
4. Где видео «стоит» — картинка почти не меняется дольше 3 секунд?
5. Где бы ты ушёл и почему?
6. Что могло задеть верующего или неверующего — в словах или в картинке?
7. Финал и надпись в конце: понятно, что делать дальше? Хочется посмотреть другую часть?
8. Оценка 1–10 и одна главная правка (в картинке или в тексте).
"""


def main(dst):
    dst = Path(dst)
    for n in (1, 2):
        work = ROOT / f"eps/god_future_p{n}"
        bv = work / "qa/blind_view"
        text = (bv / f"p{n}_text.md").read_text()
        sheets = sorted(bv.glob(f"p{n}_sheet_*.jpg"), key=lambda p: int(re.findall(r"_(\d+)\.jpg$", p.name)[0]))
        d = dst / f"p{n}"
        d.mkdir(parents=True, exist_ok=True)
        (d / "00_intro.md").write_text(INTRO)
        desc = (work / "delivery/description.txt").read_text().strip()
        (d / "zz_questions.md").write_text(QUESTIONS + "9. Описание под видео (ниже): понятно ли, зовёт ли написать комментарий, есть ли что-то лишнее, обидное "
                                           "или неправдоподобное? Что поправить?\n\n---\n" + desc + "\n")
        head = [l for l in text.splitlines() if not l.startswith("[")]
        lines = [l for l in text.splitlines() if l.startswith("[")]
        for k, sh in enumerate(sheets, 1):
            lo, hi = (k - 1) * 60, k * 60
            sec = lambda l: (lambda m: int(m.group(1)) * 60 + float(m.group(2)))(re.match(r"\[(\d+):([\d.]+)\]", l))
            mine = [l for l in lines if lo <= sec(l) < hi]
            body = (f"# Минута {k} из {len(sheets)} (с {lo} по {hi} с)\n\n" + "\n".join(head[:3]) + "\n\n" +
                    ("\n".join(mine) if mine else "(в эту минуту новых фраз нет — продолжается прошлая)") + "\n")
            (d / f"seg{k:02d}.md").write_text(body)
            shutil.copy(sh, d / f"seg{k:02d}.jpg")
        print(f"p{n}: {len(sheets)} листов -> {d}")


if __name__ == "__main__":
    main(sys.argv[1])
